    fn output_panel(&mut self, ui: &mut egui::Ui) {
        let lang = self.lang();
        ui.add_space(4.0);
        ui.horizontal(|ui| {
            let errs = self
                .diagnostics
                .iter()
                .filter(|d| d.severity == Severity::Error)
                .count();
            let warns = self
                .diagnostics
                .iter()
                .filter(|d| d.severity == Severity::Warning)
                .count();
            let label = if errs > 0 {
                format!(
                    "{} — {}",
                    tr!(lang, "diag.heading"),
                    tr!(lang, "diag.errors", n = errs)
                )
            } else if warns > 0 {
                format!(
                    "{} — {}",
                    tr!(lang, "diag.heading"),
                    tr!(lang, "diag.warnings", n = warns)
                )
            } else {
                tr!(lang, "diag.heading")
            };
            ui.selectable_value(&mut self.bottom, BottomTab::Messages, label);
            ui.selectable_value(
                &mut self.bottom,
                BottomTab::Details,
                tr!(lang, "diag.details"),
            );

            ui.with_layout(egui::Layout::right_to_left(egui::Align::Center), |ui| {
                if ui.button(tr!(lang, "diag.copy")).clicked() {
                    let text = match &self.build {
                        BuildState::Done(o) => o.raw.clone(),
                        _ => String::new(),
                    };
                    ui.ctx().copy_text(text);
                }
            });
        });
        ui.separator();

        match self.bottom {
            BottomTab::Messages => self.messages_ui(ui),
            BottomTab::Details => {
                let raw = match &self.build {
                    BuildState::Done(o) => o.raw.clone(),
                    _ => String::new(),
                };
                egui::ScrollArea::both().show(ui, |ui| {
                    ui.add(
                        egui::TextEdit::multiline(&mut raw.as_str())
                            .font(egui::TextStyle::Monospace)
                            .desired_width(f32::INFINITY),
                    );
                });
            }
        }
    }

    fn messages_ui(&mut self, ui: &mut egui::Ui) {
        let lang = self.lang();
        if self.diagnostics.is_empty() {
            ui.add_space(8.0);
            ui.label(egui::RichText::new(tr!(lang, "diag.none")).weak());
            return;
        }
        egui::ScrollArea::vertical().show(ui, |ui| {
            for d in &self.diagnostics {
                let (color, tag) = match d.severity {
                    Severity::Error => (theme::error_color(ui), "•"),
                    Severity::Warning => (theme::warning_color(ui), "•"),
                    Severity::Note => (ui.visuals().text_color(), "·"),
                };
                ui.horizontal_wrapped(|ui| {
                    ui.colored_label(color, tag);
                    ui.vertical(|ui| {
                        let where_ = match (&d.file, d.line, d.col) {
                            (Some(f), Some(l), Some(c)) => {
                                format!("{f} — {}", tr!(lang, "diag.at_line", line = l, col = c))
                            }
                            (Some(f), _, _) => f.clone(),
                            _ => String::new(),
                        };
                        if !where_.is_empty() {
                            ui.label(egui::RichText::new(where_).strong());
                        }
                        ui.colored_label(color, &d.message);
                        for s in &d.snippet {
                            ui.label(egui::RichText::new(s).monospace().small());
                        }
                    });
                });
                ui.separator();
            }
        });
    }

