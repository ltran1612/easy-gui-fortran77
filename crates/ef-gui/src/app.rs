    /// The list keys are chosen at run time, so `xtask check-hygiene`'s grep over
    /// literal `tr!` call sites cannot see them. Without this they would be the
    /// only interface strings nothing verified — and a missing Vietnamese entry
    /// does not fail loudly, it silently shows English to someone who does not
    /// read it. Checked against each catalog's own key set for that reason, not
    /// through `lookup`, which falls back to English and would hide it.
    #[test]
    fn every_file_list_key_exists_in_both_catalogs() {
        for kind in [ListKind::Sources, ListKind::Libraries] {
            let k = kind.keys();
            for key in [
                k.heading,
                k.add,
                k.empty,
                k.remove,
                k.order_hint,
                k.readonly_note,
            ] {
                for lang in [Lang::Vi, Lang::En] {
                    assert!(
                        keys(lang).contains(&key),
                        "{key} ({kind:?}) is missing from the {lang:?} catalog"
                    );
                }
            }
        }
    }

    /// Every extension the dialogs offer must be one the rest of the application
    /// agrees is that kind of file.
    #[test]
    fn the_dialog_offers_only_extensions_the_core_knows() {
        assert!(
            ListKind::Sources.extensions().contains(&"for"),
            "legacy sources are .FOR"
        );
        assert!(ListKind::Libraries.extensions().contains(&"lib"));
        for kind in [ListKind::Sources, ListKind::Libraries] {
            for e in kind.extensions() {
                assert_eq!(*e, e.to_ascii_lowercase(), "stored lowercase, cased at use");
            }
        }
    }
